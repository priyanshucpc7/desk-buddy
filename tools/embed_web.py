#!/usr/bin/env python3
"""Embed the browser UI into the firmware as a gzip blob.

Run from anywhere:  python3 tools/embed_web.py
Writes firmware/DeskBuddy/web_ui.h (checked in, so local builds work without
running this, but CI regenerates it to stay in sync).
"""
import gzip
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "web" / "index.html"
OUT = ROOT / "firmware" / "DeskBuddy" / "web_ui.h"


def c_array(name: str, data: bytes) -> str:
    lines = [f"static const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i : i + 16])
        lines.append("  " + chunk + ",")
    lines.append("};")
    lines.append(f"static const uint32_t {name}_LEN = {len(data)};")
    return "\n".join(lines)


def main() -> int:
    if not SRC.exists():
        print(f"missing {SRC}", file=sys.stderr)
        return 1
    raw = SRC.read_bytes()
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    header = (
        "// Generated by tools/embed_web.py - do not edit by hand.\n"
        "// Source: web/index.html\n"
        "#pragma once\n"
        "#include <Arduino.h>\n\n"
        + c_array("WEB_UI_GZ", gz)
        + "\n"
    )
    OUT.write_text(header)
    print(f"{SRC.name}: {len(raw)} bytes -> {len(gz)} gzipped -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
